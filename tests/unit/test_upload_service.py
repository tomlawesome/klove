@pytest.mark.asyncio
@pytest.mark.parametrize("failure", ["upload", "metadata", "download", "metadata_after"])
async def test_every_transport_ambiguity_is_unknown_and_never_retried(failure: str) -> None:
    candidate, qualification = candidate_and_qualification()
    transport = FakeTransport()
    path = f"klove/{qualification.operation_id}.gcode"
    transport.last_size = len(GCODE)
    if failure == "upload":
        transport.upload_error = True
    elif failure == "metadata":
        transport.metadata_values = [UploadTransportError()]
    elif failure == "download":
        transport.download_error = True
    else:
        transport.metadata_values = [
            transport.metadata_for(path),
            UploadTransportError(),
        ]
    uploader = service(transport)

    first = await uploader.execute(candidate, qualification)
    second = await uploader.execute(candidate, qualification)

    assert first == second
    assert_failure(
        first,
        UploadState.OUTCOME_UNKNOWN,
        UploadBoundary.TRANSPORT,
        UploadFailureCode.TRANSPORT_AMBIGUOUS,
    )
    assert len(transport.uploads) == 1


