def archive_bytes() -> bytes:
    target = BytesIO()
    with ZipFile(target, mode="w", compression=ZIP_DEFLATED) as bundle:
        bundle.writestr("[Content_Types].xml", b"<Types/>")
        bundle.writestr("_rels/.rels", b"<Relationships/>")
        bundle.writestr("3D/3dmodel.model", b"<model/>")
        bundle.writestr(SELECTED_PATH, GCODE)
    return target.getvalue()


def candidate_and_qualification() -> tuple[ValidatedGcodeCandidate, ArtifactQualification]:
    payload = archive_bytes()
    accepted = ArtifactIntent.model_validate_json(
        (FIXTURES / "accepted-intent.json").read_text(encoding="utf-8")
    )
    artifact = accepted.artifact.model_copy(
        update={
            "archive_sha256": "sha256:" + hashlib.sha256(payload).hexdigest(),
            "compressed_size_bytes": len(payload),
        }
    )
    intent = ArtifactIntent(
        contract_version=CONTRACT_VERSION,
        operation_id=accepted.operation_id,
        idempotency_key=accepted.idempotency_key,
        artifact=artifact,
        selected_plate=PlateSelection(plate_id="1", archive_path=SELECTED_PATH),
        target=target_for_safety_profile(profile()),
    )
    inspected = inspect_gcode_3mf(intent, payload, limits=ArtifactLimits())
    assert isinstance(inspected, ValidatedGcodeCandidate)
    qualification = ArtifactQualification(
        approval_id="44444444-4444-4444-8444-444444444444",
        authority_id="grove-slicer-registry",
        operation_id=intent.operation_id,
        idempotency_key=intent.idempotency_key,
        artifact=artifact,
        selected_plate=inspected.inspection.selected_plate,
        target=intent.target,
    )
    return inspected, qualification


