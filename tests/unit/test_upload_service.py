@pytest.mark.asyncio
async def test_preflight_and_selected_member_errors_are_bounded_denials(
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    candidate, qualification = candidate_and_qualification()
    transport = FakeTransport()

    def broken_inspection(*_args: object, **_kwargs: object) -> object:
        raise ValueError("hostile detail")

    monkeypatch.setattr(upload_module, "inspect_gcode_3mf", broken_inspection)
    result = await service(transport).execute(candidate, qualification)
    assert_failure(
        result,
        UploadState.DENIED,
        UploadBoundary.SOURCE,
        UploadFailureCode.SOURCE_INVALID,
    )

    monkeypatch.undo()

    class BrokenContext:
        def __enter__(self) -> BinaryIO:
            raise ValueError("hostile detail")

        def __exit__(self, *_args: object) -> None:
            return None

    def broken_open(_candidate: ValidatedGcodeCandidate) -> BrokenContext:
        return BrokenContext()

    monkeypatch.setattr(upload_module, "open_selected_gcode", broken_open)
    result = await service(transport).execute(candidate, qualification)
    assert_failure(
        result,
        UploadState.DENIED,
        UploadBoundary.SOURCE,
        UploadFailureCode.SOURCE_INVALID,
    )
    assert "hostile" not in result.model_dump_json()


