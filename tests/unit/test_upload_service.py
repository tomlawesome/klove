class FakeClock:
    def __init__(self) -> None:
        self.now = 0.0

    def __call__(self) -> float:
        return self.now

    async def sleep(self, delay: float) -> None:
        self.now += delay


class FakeTransport:
    def __init__(self) -> None:
        self.uploads: list[tuple[str, bytes, str, int]] = []
        self.upload_entered = asyncio.Event()
        self.release_upload = asyncio.Event()
        self.release_upload.set()
        self.last_path = ""
        self.last_content = b""
        self.last_size = 0
        self.modified = Decimal("1700000000.25")
        self.metadata_values: list[MoonrakerGcodeMetadata | Exception | None] = []
        self.metadata_calls = 0
        self.upload_error = False
        self.download_error = False
        self.receipt_path: str | None = None
        self.receipt_size: int | None = None
        self.remote_size: int | None = None
        self.remote_digest: str | None = None

    async def upload(
        self, path: str, content: BinaryIO, sha256: str, size_bytes: int
    ) -> MoonrakerUploadReceipt:
        self.upload_entered.set()
        await self.release_upload.wait()
        value = content.read()
        self.uploads.append((path, value, sha256, size_bytes))
        self.last_path = path
        self.last_content = value
        self.last_size = size_bytes
        if self.upload_error:
            raise UploadTransportError
        return MoonrakerUploadReceipt(
            path=self.receipt_path or path,
            size_bytes=self.receipt_size or size_bytes,
            modified=self.modified,
        )

    async def metadata(self, path: str) -> MoonrakerGcodeMetadata | None:
        self.metadata_calls += 1
        if self.metadata_values:
            value = self.metadata_values.pop(0)
            if isinstance(value, Exception):
                raise value
            return value
        return self.metadata_for(path)

    def metadata_for(self, requested_path: str, **updates: object) -> MoonrakerGcodeMetadata:
        values: dict[str, object] = {
            "path": requested_path,
            "size_bytes": self.last_size,
            "modified": self.modified,
            "metadata_uuid": "55555555-5555-4555-8555-555555555555",
            "file_processors": (),
            "nozzle_diameter_micrometres": 400,
            "gcode_start_byte": 1,
            "gcode_end_byte": self.last_size,
            "job_id": None,
            "print_start_time": None,
        }
        values.update(updates)
        return MoonrakerGcodeMetadata.model_validate(values)

    async def download(self, path: str, expected_size: int) -> RemoteFileDigest:
        if self.download_error:
            raise UploadTransportError
        assert path == self.last_path
        assert expected_size == self.last_size
        return RemoteFileDigest(
            size_bytes=self.remote_size or len(self.last_content),
            sha256=self.remote_digest or "sha256:" + hashlib.sha256(self.last_content).hexdigest(),
        )


def service(
    transport: FakeTransport,
    *,
    configured_printer: PrinterConfig | None = None,
    capacity: int = 10,
    clock: FakeClock | None = None,
) -> UploadService:
    fake_clock = clock or FakeClock()
    return UploadService(
        configured_printer or printer(),
        transport,
        limits=ArtifactLimits(
            metadata_wait_seconds=0.2,
            metadata_poll_interval_seconds=0.1,
            upload_idempotency_capacity=capacity,
        ),
        clock=fake_clock,
        sleep=fake_clock.sleep,
    )


def assert_failure(
    result: UploadOperationResult,
    state: UploadState,
    boundary: UploadBoundary,
    code: UploadFailureCode,
) -> None:
    assert result.state is state
    assert result.failure is not None
    assert result.failure.boundary is boundary
    assert result.failure.code is code
    assert result.verified is None


@pytest.mark.asyncio
async def test_success_is_single_dispatch_and_duplicate_reuses_exact_evidence() -> None:
    candidate, qualification = candidate_and_qualification()
    transport = FakeTransport()
    uploader = service(transport)

    first = await uploader.execute(candidate, qualification)
    second = await uploader.execute(candidate, qualification)

    assert first == second
    assert first.state is UploadState.VERIFIED
    assert first.verified is not None
    assert first.verified.remote_file.sha256 == qualification.selected_plate.gcode_sha256
    assert transport.uploads == [
        (
            f"klove/{qualification.operation_id}.gcode",
            GCODE,
            qualification.selected_plate.gcode_sha256,
            len(GCODE),
        )
    ]
    assert transport.metadata_calls == 2


@pytest.mark.asyncio
async def test_caller_cancellation_is_shielded_and_duplicate_completes_original() -> None:
    candidate, qualification = candidate_and_qualification()
    transport = FakeTransport()
    transport.release_upload.clear()
    uploader = service(transport)

    caller = asyncio.create_task(uploader.execute(candidate, qualification))
    await transport.upload_entered.wait()
    caller.cancel()
    with pytest.raises(asyncio.CancelledError):
        await caller
    duplicate = asyncio.create_task(uploader.execute(candidate, qualification))
    transport.release_upload.set()

    assert (await duplicate).state is UploadState.VERIFIED
    assert len(transport.uploads) == 1


@pytest.mark.asyncio
async def test_distinct_operations_are_serialized_for_the_printer() -> None:
    candidate, qualification = candidate_and_qualification()
    transport = FakeTransport()
    transport.release_upload.clear()
    uploader = service(transport)
    second_qualification = qualification.model_copy(
        update={
            "operation_id": "66666666-6666-4666-8666-666666666666",
            "idempotency_key": "77777777-7777-4777-8777-777777777777",
        }
    )

    first = asyncio.create_task(uploader.execute(candidate, qualification))
    await transport.upload_entered.wait()
    second = asyncio.create_task(uploader.execute(candidate, second_qualification))
    await asyncio.sleep(0)
    assert len(transport.uploads) == 0
    transport.release_upload.set()

    assert (await first).state is UploadState.VERIFIED
    assert (await second).state is UploadState.VERIFIED
    assert [item[0] for item in transport.uploads] == [
        f"klove/{qualification.operation_id}.gcode",
        f"klove/{second_qualification.operation_id}.gcode",
    ]


