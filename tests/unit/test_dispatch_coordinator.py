@pytest.mark.asyncio
async def test_initialize_fails_closed_and_only_schedules_safe_own_continuations(
    tmp_path: Path,
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    value, _admissions = await coordinator(tmp_path, Remote())
    submitted = request(archive())

    class BrokenJournal:
        def initialize(self) -> None:
            raise JournalError

    install_journal(value, BrokenJournal())
    await value.initialize()
    assert value._ready is False

    class ReconciliationSpool:
        def initialize(self) -> None:
            return None

        def operation_ids(self) -> frozenset[str]:
            return frozenset()

        def verify(self, _request: DispatchRequest) -> None:
            return None

        def remove(self, _request: DispatchRequest) -> None:
            return None

    value._spool = ReconciliationSpool()  # type: ignore[assignment]

    own = durable(submitted, DispatchState.ACCEPTED)
    foreign_request = submitted.model_copy(
        update={"printer_uuid": "55555555-5555-4555-8555-555555555555"}
    )
    foreign = DispatchJournalRecord(
        grant=DispatchGrant(principal_id="grove-worker", printer_uuid=foreign_request.printer_uuid),
        request=foreign_request,
        state=DispatchState.ACCEPTED,
    )

    class RecoveringJournal:
        def initialize(self) -> None:
            return None

        def records(self) -> tuple[DispatchJournalRecord, ...]:
            return foreign, own

    scheduled: list[DispatchJournalRecord] = []

    async def schedule(record: DispatchJournalRecord) -> None:
        scheduled.append(record)

    install_journal(value, RecoveringJournal())
    monkeypatch.setattr(value, "_recover_record", lambda record: record)
    monkeypatch.setattr(value, "_schedule", schedule)
    await value.initialize()

    assert bool(value._ready)
    assert scheduled == [own]

    printing = own.model_copy(update={"state": DispatchState.PRINTING})
    starting = own.model_copy(update={"state": DispatchState.STARTING})
    terminal = DispatchJournalRecord(
        grant=grant(),
        request=submitted,
        state=DispatchState.FAILED,
        failure=DispatchFailure(code=DispatchFailureCode.SOURCE_INVALID),
    )

    class ReconcileJournal:
        def initialize(self) -> None:
            return None

        def records(self) -> tuple[DispatchJournalRecord, ...]:
            return terminal, printing, starting

    reconciled: list[DispatchState] = []

    async def reconcile_printing(record: DispatchJournalRecord) -> DispatchJournalRecord:
        reconciled.append(record.state)
        return own

    async def reconcile_started(
        record: DispatchJournalRecord, *, resume_missing_start: bool
    ) -> DispatchJournalRecord:
        assert resume_missing_start is True
        reconciled.append(record.state)
        return own

    install_journal(value, ReconcileJournal())
    monkeypatch.setattr(value, "_reconcile_printing", reconcile_printing)
    monkeypatch.setattr(value, "_reconcile_started", reconcile_started)
    scheduled.clear()
    await value.initialize()
    assert reconciled == [DispatchState.PRINTING, DispatchState.STARTING]
    assert scheduled == [own, own]

    async def failed_reconcile(_record: DispatchJournalRecord) -> DispatchJournalRecord:
        raise JournalError

    value._ready = True
    monkeypatch.setattr(value, "_reconcile_printing", failed_reconcile)
    await value.initialize()
    assert value._ready is False


