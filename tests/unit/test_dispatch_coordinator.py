class Registry:
    def __init__(self) -> None:
        self.record = registered_printer(safety_profiles=(safety_profile(),))

    def get(self, printer_uuid: str) -> RegisteredPrinter | None:
        return self.record if printer_uuid == self.record.printer_uuid else None


class InMemoryJournal:
    def __init__(self, current: DispatchJournalRecord | None, *, failure: bool = False) -> None:
        self.current = current
        self.failure = failure

    def lookup(self, _operation_id: str, _idempotency_key: str) -> DispatchJournalRecord | None:
        if self.failure:
            raise JournalError
        return self.current

    def initialize(self) -> None:
        if self.failure:
            raise JournalError

    def records(self) -> tuple[DispatchJournalRecord, ...]:
        if self.failure:
            raise JournalError
        return () if self.current is None else (self.current,)

    def replace(
        self, expected: DispatchJournalRecord, updated: DispatchJournalRecord
    ) -> DispatchJournalRecord:
        if self.failure:
            raise JournalError
        assert self.current == expected
        self.current = updated
        return updated


def install_journal(coordinator: DispatchCoordinator, journal: object) -> None:
    """Install a deliberately narrow journal double without widening production types."""
    coordinator._journal = cast(DispatchJournal, journal)


class Remote:
    def __init__(self) -> None:
        self.files: dict[str, tuple[bytes, MoonrakerGcodeMetadata]] = {}
        self.uploads: list[str] = []
        self.dispatches: list[str] = []
        self.fail_upload = False
        self.fail_queries = False
        self.fail_after_query: int | None = None
        self.query_count = 0
        self.query_entered = asyncio.Event()
        self.release_query = asyncio.Event()
        self.release_query.set()
        self.status = JobHistoryStatus.IN_PROGRESS
        self.upload_entered = asyncio.Event()
        self.release_upload = asyncio.Event()
        self.release_upload.set()

    async def upload(
        self, path: str, content: BinaryIO, sha256: str, size_bytes: int
    ) -> MoonrakerUploadReceipt:
        self.upload_entered.set()
        await self.release_upload.wait()
        if self.fail_upload:
            raise UploadTransportError
        data = content.read()
        assert len(data) == size_bytes
        assert sha256 == "sha256:" + hashlib.sha256(data).hexdigest()
        modified = Decimal("1700000000.25")
        metadata = MoonrakerGcodeMetadata(
            path=path,
            size_bytes=len(data),
            modified=modified,
            metadata_uuid="44444444-4444-4444-8444-444444444444",
            file_processors=(),
            nozzle_diameter_micrometres=400,
            gcode_start_byte=1,
            gcode_end_byte=len(data),
            job_id=None,
            print_start_time=None,
        )
        self.files[path] = (data, metadata)
        self.uploads.append(path)
        return MoonrakerUploadReceipt(path=path, size_bytes=len(data), modified=modified)

    async def metadata(self, path: str) -> MoonrakerGcodeMetadata | None:
        file = self.files.get(path)
        return None if file is None else file[1]

    async def download(self, path: str, expected_size: int) -> RemoteFileDigest:
        data, _metadata = self.files[path]
        assert len(data) == expected_size
        return RemoteFileDigest(
            size_bytes=len(data), sha256="sha256:" + hashlib.sha256(data).hexdigest()
        )

    async def query(self) -> StartObservation:
        self.query_count += 1
        self.query_entered.set()
        await self.release_query.wait()
        if self.fail_queries and self.dispatches:
            raise StartTransportError
        if self.fail_after_query is not None and self.query_count > self.fail_after_query:
            raise StartTransportError
        if not self.dispatches:
            return StartObservation(
                eventtime=10,
                phase=PrinterPhase.IDLE,
                filename="",
                file_position=0,
                latest_job=None,
            )
        path = self.dispatches[-1]
        phase = (
            PrinterPhase.PRINTING
            if self.status is JobHistoryStatus.IN_PROGRESS
            else PrinterPhase.COMPLETED
            if self.status is JobHistoryStatus.COMPLETED
            else PrinterPhase.CANCELLED
            if self.status is JobHistoryStatus.CANCELLED
            else PrinterPhase.ERROR
        )
        return StartObservation(
            eventtime=11,
            phase=phase,
            filename=path,
            file_position=10,
            latest_job=JobIdentitySnapshot(
                job_id="000002",
                filename=path,
                start_time=1_700_000_100,
                status=self.status,
            ),
        )

    async def dispatch(self, path: str) -> None:
        self.dispatches.append(path)


async def eventually(
    coordinator: DispatchCoordinator,
    submitted: DispatchRequest,
    *,
    expected: DispatchState,
) -> None:
    for _ in range(100):
        result = await coordinator.result(
            grant(), submitted.operation_id, submitted.idempotency_key
        )
        if result is not None and result.state is expected:
            return
        await asyncio.sleep(0)
    pytest.fail(f"operation did not reach {expected.value}")


async def coordinator(
    tmp_path: Path,
    remote: Remote,
    registry: Registry | None = None,
    *,
    receive_timeout_seconds: float = 300.0,
    receive_limiter: DispatchReceiveLimiter | None = None,
) -> tuple[DispatchCoordinator, PrinterAdmissionGates]:
    state = tmp_path / "state"
    state.mkdir(mode=0o700)
    state.chmod(0o700)
    admissions = PrinterAdmissionGates()
    limits = ArtifactLimits(metadata_wait_seconds=0.1, metadata_poll_interval_seconds=0.01)
    uploader = UploadService(printer_config(), remote, limits=limits, admissions=admissions)
    starter = StartService(
        printer_config(),
        remote,
        StartJournal(state / "start.sqlite3"),
        enabled=True,
        confirmation_timeout_seconds=0.1,
        poll_interval_seconds=0.01,
        admissions=admissions,
    )
    await starter.initialize()
    value = DispatchCoordinator(
        PRINTER_UUID,
        registry or Registry(),
        uploader,
        starter,
        DispatchJournal(state / "dispatch.sqlite3"),
        DispatchSpool(state / "spool", limits=limits),
        limits=limits,
        operation_capacity=8,
        admissions=admissions,
        receive_limiter=receive_limiter or DispatchReceiveLimiter(4),
        receive_timeout_seconds=receive_timeout_seconds,
    )
    spool = state / "spool"
    spool.mkdir(mode=0o700)
    spool.chmod(0o700)
    await value.initialize()
    return value, admissions


