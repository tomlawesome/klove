@pytest.mark.asyncio
async def test_task_bookkeeping_and_run_fail_closed_on_missing_or_unexpected_state(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    value, _admissions = await coordinator(tmp_path, Remote())
    submitted = request(archive())
    accepted = durable(submitted, DispatchState.ACCEPTED)
    blocker = asyncio.Event()

    async def blocked() -> None:
        await blocker.wait()

    running = asyncio.create_task(blocked())
    value._tasks[submitted.operation_id] = running
    await value._schedule(accepted)
    assert value._tasks[submitted.operation_id] is running
    value._forget_task(submitted.operation_id, asyncio.create_task(asyncio.sleep(0)))
    assert value._tasks[submitted.operation_id] is running
    running.cancel()
    with pytest.raises(asyncio.CancelledError):
        await running

    install_journal(value, InMemoryJournal(None))
    await value._run(submitted.operation_id, submitted.idempotency_key)

    install_journal(value, InMemoryJournal(None, failure=True))
    await value._run(submitted.operation_id, submitted.idempotency_key)
    install_journal(value, InMemoryJournal(accepted))
    monkeypatch.setattr(
        value, "_qualify_and_upload", lambda _record: (_ for _ in ()).throw(RuntimeError)
    )
    terminals: list[DispatchFailureCode] = []

    def terminal(
        _record: DispatchJournalRecord, _state: DispatchState, code: DispatchFailureCode
    ) -> DispatchJournalRecord:
        terminals.append(code)
        return accepted

    monkeypatch.setattr(value, "_terminal", terminal)
    await value._run(submitted.operation_id, submitted.idempotency_key)

    class SequenceJournal:
        def __init__(self, final: DispatchJournalRecord | None) -> None:
            self.calls = 0
            self.final = final

        def lookup(self, _operation_id: str, _idempotency_key: str) -> DispatchJournalRecord | None:
            self.calls += 1
            return accepted if self.calls == 1 else self.final

    for state, _expected in (
        (DispatchState.UPLOADING, DispatchFailureCode.UPLOAD_AMBIGUOUS),
        (DispatchState.STARTING, DispatchFailureCode.START_AMBIGUOUS),
        (DispatchState.FAILED, DispatchFailureCode.SOURCE_INVALID),
    ):
        final = (
            DispatchJournalRecord(
                grant=grant(),
                request=submitted,
                state=state,
                failure=DispatchFailure(code=DispatchFailureCode.SOURCE_INVALID),
            )
            if state is DispatchState.FAILED
            else accepted.model_copy(update={"state": state})
        )
        install_journal(value, SequenceJournal(final))
        await value._run(submitted.operation_id, submitted.idempotency_key)

    install_journal(value, SequenceJournal(None))
    await value._run(submitted.operation_id, submitted.idempotency_key)

    class ErrorAfterFailureJournal:
        calls = 0

        def lookup(self, _operation_id: str, _idempotency_key: str) -> DispatchJournalRecord:
            self.calls += 1
            if self.calls == 1:
                return accepted
            raise JournalError

    install_journal(value, ErrorAfterFailureJournal())
    await value._run(submitted.operation_id, submitted.idempotency_key)

    assert terminals == [
        DispatchFailureCode.INTERNAL_FAILURE,
        DispatchFailureCode.UPLOAD_AMBIGUOUS,
        DispatchFailureCode.START_AMBIGUOUS,
    ]


