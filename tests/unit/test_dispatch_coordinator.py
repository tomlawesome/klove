@pytest.mark.asyncio
async def test_cancel_wins_when_it_arrives_after_receive_before_acceptance(
    tmp_path: Path,
) -> None:
    value, _admissions = await coordinator(tmp_path, Remote())
    submitted = request(archive())

    class OrderedGates:
        def __init__(self) -> None:
            self._inner = PrinterAdmissionGates()
            self._calls = 0
            self.post_receive_attempted = asyncio.Event()
            self.release_post_receive = asyncio.Event()

        @asynccontextmanager
        async def hold(self, printer_uuid: str) -> AsyncIterator[None]:
            self._calls += 1
            call = self._calls
            if call == 2:
                self.post_receive_attempted.set()
                await self.release_post_receive.wait()
            async with self._inner.hold(printer_uuid):
                yield
            if call == 3:
                self.release_post_receive.set()

    gates = OrderedGates()
    value._admissions = gates  # type: ignore[assignment]

    submitting = asyncio.create_task(value.submit(grant(), submitted, stream(archive())))
    await gates.post_receive_attempted.wait()
    cancelling = asyncio.create_task(
        value.cancel(grant(), submitted.operation_id, submitted.idempotency_key)
    )

    accepted, cancelled = await asyncio.gather(submitting, cancelling)

    assert accepted.state is DispatchState.CANCELLED
    assert cancelled is not None and cancelled.state is DispatchState.CANCELLED


