@pytest.mark.asyncio
async def test_transport_uses_exact_non_actuating_upload_and_verifies_remote_bytes() -> None:
    observed: dict[str, object] = {}

    async def upload(request: web.Request) -> web.Response:
        assert request.headers["X-Api-Key"] == API_KEY
        fields: dict[str, object] = {}
        reader = await request.multipart()
        while part := await reader.next():
            assert isinstance(part, aiohttp.BodyPartReader)
            if part.name == "file":
                fields["file"] = await part.read()
                fields["filename"] = part.filename
                fields["file_content_type"] = part.headers["Content-Type"]
            else:
                fields[str(part.name)] = await part.text()
        observed["upload"] = fields
        response_document = upload_document()
        response_document["item"] = {
            **copy.deepcopy(response_document["item"]),  # type: ignore[arg-type]
            "modified": MODIFIED,
        }
        return web.json_response(
            response_document,
            status=201,
            headers={"Location": f"/server/files/gcodes/{PATH}"},
        )

    async def metadata(request: web.Request) -> web.Response:
        assert request.headers["X-Api-Key"] == API_KEY
        observed["metadata_filename"] = request.query.getall("filename")
        result = metadata_result()
        result["modified"] = MODIFIED
        result["nozzle_diameter"] = 0.4
        return web.json_response({"result": result})

    async def download(request: web.Request) -> web.Response:
        assert request.headers["X-Api-Key"] == API_KEY
        observed["download_path"] = request.path
        return web.Response(body=DATA, content_type="application/octet-stream")

    application = web.Application()
    application.router.add_post("/server/files/upload", upload)
    application.router.add_get("/server/files/metadata", metadata)
    application.router.add_get(f"/server/files/gcodes/{PATH}", download)
    async with TestServer(application) as server, aiohttp.ClientSession() as session:
        transport = MoonrakerUploadTransport(
            config(str(server.make_url(""))),
            API_KEY,
            session,
            request_timeout_seconds=1,
        )
        receipt = await transport.upload(PATH, BytesIO(DATA), DIGEST, len(DATA))
        metadata_value = await transport.metadata(PATH)
        remote = await transport.download(PATH, len(DATA))

    assert receipt.path == PATH
    assert receipt.modified == Decimal(str(MODIFIED))
    assert metadata_value == MoonrakerGcodeMetadata(
        path=PATH,
        size_bytes=len(DATA),
        modified=Decimal(str(MODIFIED)),
        metadata_uuid="44444444-4444-4444-8444-444444444444",
        file_processors=(),
        nozzle_diameter_micrometres=400,
        gcode_start_byte=1,
        gcode_end_byte=len(DATA),
        job_id=None,
        print_start_time=None,
    )
    assert remote.size_bytes == len(DATA)
    assert remote.sha256 == DIGEST
    assert observed == {
        "upload": {
            "root": "gcodes",
            "path": "klove",
            "checksum": DIGEST.removeprefix("sha256:"),
            "print": "false",
            "file": DATA,
            "filename": PATH.removeprefix("klove/"),
            "file_content_type": "application/octet-stream",
        },
        "metadata_filename": [PATH],
        "download_path": f"/server/files/gcodes/{PATH}",
    }


