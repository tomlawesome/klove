def test_metadata_decoder_accepts_only_exact_safety_evidence() -> None:
    decoded = _decode_metadata({"result": metadata_result()}, PATH)
    assert decoded.nozzle_diameter_micrometres == 400
    assert decoded.job_id is None

    invalid: list[object] = [
        [],
        {},
        {"result": metadata_result(), "extra": True},
        {"result": []},
        {"result": {"filename": PATH}},
    ]
    for document in invalid:
        with pytest.raises(UploadTransportError):
            _decode_metadata(document, PATH)


