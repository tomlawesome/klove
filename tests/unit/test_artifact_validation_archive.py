def test_strict_zip64_rejects_malformed_and_multi_disk_extensions() -> None:
    payload = as_zip64(zip_bytes())
    eocd = len(payload) - 22
    locator = eocd - 20
    record = locator - 56

    minimal_eocd = bytearray(22)
    struct.pack_into(
        "<4s4H2LH",
        minimal_eocd,
        0,
        b"PK\x05\x06",
        0,
        0,
        0xFFFF,
        0xFFFF,
        0xFFFFFFFF,
        0xFFFFFFFF,
        0,
    )
    assert_failure(
        inspect(bytes(minimal_eocd)), ArtifactBoundary.ARCHIVE, ArtifactFailureCode.MALFORMED
    )

    mutations = (
        (
            bytes(bytearray(payload[:locator]) + b"bad!" + payload[locator + 4 :]),
            ArtifactFailureCode.MALFORMED,
        ),
        (patch_u32(payload, locator + 4, 1), ArtifactFailureCode.UNSUPPORTED_ARCHIVE),
        (
            bytes(bytearray(payload[:record]) + b"bad!" + payload[record + 4 :]),
            ArtifactFailureCode.MALFORMED,
        ),
        (patch_u32(payload, record + 4, 43), ArtifactFailureCode.MALFORMED),
        (patch_u16(payload, record + 14, 46), ArtifactFailureCode.UNSUPPORTED_ARCHIVE),
        (patch_u32(payload, record + 16, 1), ArtifactFailureCode.UNSUPPORTED_ARCHIVE),
        (patch_u32(payload, record + 48, 1), ArtifactFailureCode.MALFORMED),
        (patch_u16(payload, eocd + 8, 1), ArtifactFailureCode.MALFORMED),
    )
    for changed, code in mutations:
        assert_failure(inspect(changed), ArtifactBoundary.ARCHIVE, code)

    padded = payload[:locator] + b"x" + payload[locator:]
    assert_failure(inspect(padded), ArtifactBoundary.ARCHIVE, ArtifactFailureCode.MALFORMED)


def test_low_level_zip_defences_reject_invalid_metadata_and_reads() -> None:
    info = ZipInfo("Metadata/bad")
    info.file_size = -1
    with pytest.raises(validation._Denied):
        validation._validate_zip_info(info)

    directory = ZipInfo("Metadata/")
    directory.compress_type = ZIP_DEFLATED
    directory.header_offset = 0
    with pytest.raises(validation._Denied):
        validation._validate_zip_info(directory)

    new_version = ZipInfo("Metadata/new-version")
    new_version.extract_version = 46
    new_version.header_offset = 0
    with pytest.raises(validation._Denied):
        validation._validate_zip_info(new_version)

    old_version_unknown_compression = ZipInfo("Metadata/unknown-compression")
    old_version_unknown_compression.extract_version = 20
    old_version_unknown_compression.compress_type = ZIP_BZIP2
    old_version_unknown_compression.header_offset = 0
    with pytest.raises(validation._Denied):
        validation._validate_zip_info(old_version_unknown_compression)

    class BrokenSeek(BytesIO):
        def seek(self, pos: int, whence: int = 0) -> int:
            raise OSError("hostile")

    with pytest.raises(validation._Denied):
        validation._read_exact_at(cast(validation._ImmutableBytesReader, BrokenSeek()), 0, 1)
    with pytest.raises(validation._Denied):
        validation._read_exact_at(validation._ImmutableBytesReader(b""), -1, 1)
    with pytest.raises(validation._Denied):
        validation._read_exact_at(validation._ImmutableBytesReader(b"x"), 0, 2)


def test_immutable_reader_has_bounded_standard_seek_semantics() -> None:
    reader = validation._ImmutableBytesReader(b"abcdef")

    assert reader.read() == b"abcdef"
    assert reader.seek(-2, 1) == 4
    assert reader.read(1) == b"e"
    assert reader.tell() == 5
    assert reader.seekable()
    with pytest.raises(ValueError, match="unsupported whence"):
        reader.seek(0, 3)
    with pytest.raises(ValueError, match="negative seek"):
        reader.seek(-7)


