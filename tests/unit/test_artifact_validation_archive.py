def test_entry_count_expanded_size_ratio_and_selected_size_limits_are_enforced() -> None:
    payload = zip_bytes()
    assert_failure(
        inspect(payload, limits=ArtifactLimits(max_zip_entries=1)),
        ArtifactBoundary.ARCHIVE,
        ArtifactFailureCode.LIMIT_EXCEEDED,
    )

    central = central_record_offset(payload, SELECTED_PATH)
    zero_compressed_size = patch_u32(payload, central + 20, 0)
    assert_failure(
        inspect(zero_compressed_size),
        ArtifactBoundary.ARCHIVE,
        ArtifactFailureCode.LIMIT_EXCEEDED,
    )
    assert_failure(
        inspect(
            payload,
            limits=ArtifactLimits(
                max_archive_expanded_bytes=64,
                max_gcode_bytes=64,
                max_gcode_header_bytes=64,
                max_gcode_line_bytes=64,
            ),
        ),
        ArtifactBoundary.ARCHIVE,
        ArtifactFailureCode.LIMIT_EXCEEDED,
    )
    bomb = zip_bytes(
        [*CORE_ENTRIES, ("Metadata/padding", b"A" * 4096), (SELECTED_PATH, VALID_GCODE)]
    )
    assert_failure(
        inspect(bomb, limits=ArtifactLimits(max_compression_ratio=2)),
        ArtifactBoundary.ARCHIVE,
        ArtifactFailureCode.LIMIT_EXCEEDED,
    )
    large_gcode_payload = zip_bytes(
        [*CORE_ENTRIES, (SELECTED_PATH, VALID_GCODE + b"; filler\n" * 10)]
    )
    assert_failure(
        inspect(
            large_gcode_payload,
            limits=ArtifactLimits(
                max_gcode_bytes=64,
                max_gcode_header_bytes=64,
                max_gcode_line_bytes=32,
            ),
        ),
        ArtifactBoundary.SELECTED_PLATE,
        ArtifactFailureCode.LIMIT_EXCEEDED,
    )


