FIXTURES = Path(__file__).parents[1] / "fixtures" / "artifacts"
SELECTED_PATH = "Metadata/plate_1.gcode"
VALID_GCODE = b"; generated by OrcaSlicer 2.3.0\nG28\nG1 X1.0 Y2.0\n"
CORE_ENTRIES = (
    ("[Content_Types].xml", b"<Types/>"),
    ("_rels/.rels", b"<Relationships/>"),
    ("3D/3dmodel.model", b"<model/>"),
)


def base_intent() -> ArtifactIntent:
    return ArtifactIntent.model_validate_json(
        (FIXTURES / "accepted-intent.json").read_text(encoding="utf-8")
    )


def zip_bytes(
    entries: list[tuple[str | ZipInfo, bytes]] | None = None,
    *,
    compression: int = ZIP_DEFLATED,
    archive_comment: bytes = b"",
) -> bytes:
    members: list[tuple[str | ZipInfo, bytes]] = list(CORE_ENTRIES)
    members.append((SELECTED_PATH, VALID_GCODE))
    if entries is not None:
        members = entries
    target = BytesIO()
    with ZipFile(target, mode="w", compression=compression, allowZip64=True) as bundle:
        for name, content in members:
            bundle.writestr(name, content)
        bundle.comment = archive_comment
    return target.getvalue()


def intent_for(payload: bytes, *, archive_path: str = SELECTED_PATH) -> ArtifactIntent:
    request = base_intent()
    return request.model_copy(
        update={
            "artifact": request.artifact.model_copy(
                update={
                    "archive_sha256": "sha256:" + hashlib.sha256(payload).hexdigest(),
                    "compressed_size_bytes": len(payload),
                }
            ),
            "selected_plate": request.selected_plate.model_copy(
                update={"archive_path": archive_path}
            ),
        }
    )


def inspect(payload: bytes, *, limits: ArtifactLimits | None = None) -> object:
    return validation.inspect_gcode_3mf(
        intent_for(payload),
        payload,
        limits=limits or ArtifactLimits(),
    )


def assert_failure(
    result: object,
    boundary: ArtifactBoundary,
    code: ArtifactFailureCode,
) -> None:
    assert result == ArtifactFailure(boundary=boundary, code=code)


def central_record_offset(payload: bytes, name: str) -> int:
    eocd = len(payload) - 22
    directory_offset = cast(int, struct.unpack_from("<L", payload, eocd + 16)[0])
    offset = directory_offset
    while payload[offset : offset + 4] == b"PK\x01\x02":
        name_size, extra_size, comment_size = struct.unpack_from("<3H", payload, offset + 28)
        current = payload[offset + 46 : offset + 46 + name_size].decode("utf-8")
        if current == name:
            return offset
        offset += 46 + name_size + extra_size + comment_size
    raise AssertionError(name)


def patch_u16(payload: bytes, offset: int, value: int) -> bytes:
    changed = bytearray(payload)
    struct.pack_into("<H", changed, offset, value)
    return bytes(changed)


def patch_u32(payload: bytes, offset: int, value: int) -> bytes:
    changed = bytearray(payload)
    struct.pack_into("<L", changed, offset, value)
    return bytes(changed)


def as_zip64(payload: bytes) -> bytes:
    eocd_offset = len(payload) - 22
    eocd = bytearray(payload[eocd_offset:])
    entries = struct.unpack_from("<H", eocd, 10)[0]
    directory_size = struct.unpack_from("<L", eocd, 12)[0]
    directory_offset = struct.unpack_from("<L", eocd, 16)[0]
    record = struct.pack(
        "<4sQ2H2L4Q",
        b"PK\x06\x06",
        44,
        45,
        45,
        0,
        0,
        entries,
        entries,
        directory_size,
        directory_offset,
    )
    locator = struct.pack("<4sLQL", b"PK\x06\x07", 0, eocd_offset, 1)
    struct.pack_into("<4H2L", eocd, 4, 0, 0, 0xFFFF, 0xFFFF, 0xFFFFFFFF, 0xFFFFFFFF)
    return payload[:eocd_offset] + record + locator + bytes(eocd)


@pytest.mark.parametrize(
    "name",
    [
        "../escape.gcode",
        "/absolute.gcode",
        "Metadata\\plate.gcode",
        "C:/Metadata/plate.gcode",
        "Metadata//plate.gcode",
        "Metadata/./plate.gcode",
        "Metadata/../plate.gcode",
        "Metadata/ plate.gcode",
        "Metadata/tab\tplate.gcode",
        "Metadata/pl\u00e1te.gcode",
    ],
)
def test_unsafe_member_names_are_denied(name: str) -> None:
    payload = zip_bytes([*CORE_ENTRIES, (name, b"unselected"), (SELECTED_PATH, VALID_GCODE)])

    assert_failure(
        inspect(payload),
        ArtifactBoundary.ARCHIVE,
        ArtifactFailureCode.UNSAFE_ARCHIVE,
    )


def test_nul_sanitized_duplicate_and_case_alias_names_are_denied() -> None:
    payload = zip_bytes()
    central = central_record_offset(payload, SELECTED_PATH)
    with ZipFile(BytesIO(payload)) as bundle:
        local = next(
            info.header_offset for info in bundle.infolist() if info.filename == SELECTED_PATH
        )
    nul_payload = bytearray(payload)
    nul_index = len("Metadata/plate_1")
    nul_payload[central + 46 + nul_index] = 0
    nul_payload[local + 30 + nul_index] = 0
    assert_failure(
        inspect(bytes(nul_payload)),
        ArtifactBoundary.ARCHIVE,
        ArtifactFailureCode.UNSAFE_ARCHIVE,
    )

    with pytest.warns(UserWarning, match="Duplicate name"):
        duplicate = zip_bytes(
            [*CORE_ENTRIES, (SELECTED_PATH, VALID_GCODE), (SELECTED_PATH, VALID_GCODE)]
        )
    assert_failure(
        inspect(duplicate),
        ArtifactBoundary.ARCHIVE,
        ArtifactFailureCode.UNSAFE_ARCHIVE,
    )
    case_alias = zip_bytes(
        [
            *CORE_ENTRIES,
            ("Metadata/readme.txt", b"a"),
            ("metadata/README.TXT", b"b"),
            (SELECTED_PATH, VALID_GCODE),
        ]
    )
    assert_failure(
        inspect(case_alias),
        ArtifactBoundary.ARCHIVE,
        ArtifactFailureCode.UNSAFE_ARCHIVE,
    )


def test_links_encryption_and_unsupported_zip_features_are_denied() -> None:
    link = ZipInfo("Metadata/link")
    link.create_system = 3
    link.external_attr = (stat.S_IFLNK | 0o777) << 16
    linked = zip_bytes([*CORE_ENTRIES, (link, b"target"), (SELECTED_PATH, VALID_GCODE)])
    assert_failure(inspect(linked), ArtifactBoundary.ARCHIVE, ArtifactFailureCode.UNSAFE_ARCHIVE)

    payload = zip_bytes()
    central = central_record_offset(payload, SELECTED_PATH)
    with ZipFile(BytesIO(payload)) as bundle:
        local = next(
            info.header_offset for info in bundle.infolist() if info.filename == SELECTED_PATH
        )
    encrypted = patch_u16(payload, central + 8, 1)
    encrypted = patch_u16(encrypted, local + 6, 1)
    assert_failure(inspect(encrypted), ArtifactBoundary.ARCHIVE, ArtifactFailureCode.UNSAFE_ARCHIVE)

    unsupported = zip_bytes(compression=ZIP_BZIP2)
    assert_failure(
        inspect(unsupported),
        ArtifactBoundary.ARCHIVE,
        ArtifactFailureCode.UNSUPPORTED_ARCHIVE,
    )

    unsupported_flags = patch_u16(payload, central + 8, 1 << 4)
    assert_failure(
        inspect(unsupported_flags),
        ArtifactBoundary.ARCHIVE,
        ArtifactFailureCode.UNSUPPORTED_ARCHIVE,
    )

    commented = ZipInfo("Metadata/commented")
    commented.comment = b"comment"
    with_comment = zip_bytes([*CORE_ENTRIES, (commented, b"content"), (SELECTED_PATH, VALID_GCODE)])
    assert_failure(
        inspect(with_comment),
        ArtifactBoundary.ARCHIVE,
        ArtifactFailureCode.UNSUPPORTED_ARCHIVE,
    )

    volume = patch_u16(payload, central + 34, 1)
    assert_failure(
        inspect(volume),
        ArtifactBoundary.ARCHIVE,
        ArtifactFailureCode.UNSUPPORTED_ARCHIVE,
    )


