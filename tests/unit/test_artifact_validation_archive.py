def test_conflicting_local_header_and_selected_crc_failure_are_bounded() -> None:
    payload = zip_bytes()
    with ZipFile(BytesIO(payload)) as bundle:
        selected = next(info for info in bundle.infolist() if info.filename == SELECTED_PATH)
    local = selected.header_offset
    changed_header = bytearray(payload)
    changed_header[local + 30] ^= 1
    assert_failure(
        inspect(bytes(changed_header)),
        ArtifactBoundary.ARCHIVE,
        ArtifactFailureCode.MALFORMED,
    )

    name_size, extra_size = struct.unpack_from("<2H", payload, local + 26)
    data_offset = local + 30 + name_size + extra_size
    corrupted = bytearray(payload)
    corrupted[data_offset + selected.compress_size // 2] ^= 1
    assert_failure(
        inspect(bytes(corrupted)),
        ArtifactBoundary.SELECTED_PLATE,
        ArtifactFailureCode.INTEGRITY_FAILED,
    )
