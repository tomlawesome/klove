class _Registry:
    def __init__(self, record: RegisteredPrinter) -> None:
        self._record = record

    def get(self, printer_uuid: str) -> RegisteredPrinter | None:
        return self._record if printer_uuid == self._record.printer_uuid else None


@dataclass(slots=True)
class _Runtime:
    coordinator: DispatchCoordinator
    journal: DispatchJournal
    session: aiohttp.ClientSession
    transport: MoonrakerStartTransport

    async def close(self) -> None:
        await self.session.close()


def _require(condition: bool, message: str) -> None:
    if not condition:
        raise RuntimeError(message)


def _archive() -> bytes:
    target = BytesIO()
    with ZipFile(target, mode="w", compression=ZIP_STORED) as bundle:
        bundle.writestr("[Content_Types].xml", b"<Types/>")
        bundle.writestr("_rels/.rels", b"<Relationships/>")
        bundle.writestr("3D/3dmodel.model", b"<model/>")
        bundle.writestr(SELECTED_PATH, GCODE)
    return target.getvalue()


def _request(operation_id: str, idempotency_key: str, archive: bytes) -> DispatchRequest:
    return DispatchRequest(
        operation_id=operation_id,
        idempotency_key=idempotency_key,
        printer_uuid=PRINTER_UUID,
        slicer_profile_id=PROFILE.slicer_profile_id,
        safety_profile_generation=PROFILE.generation,
        safety_profile_fingerprint=TARGET.safety_profile_fingerprint,
        selected_plate=PlateSelection(plate_id="1", archive_path=SELECTED_PATH),
        archive_sha256=f"sha256:{hashlib.sha256(archive).hexdigest()}",
        archive_size_bytes=len(archive),
    )


async def _stream(archive: bytes) -> AsyncIterator[bytes]:
    yield archive


async def _stalled_stream(entered: asyncio.Event) -> AsyncIterator[bytes]:
    entered.set()
    await asyncio.Event().wait()
    yield b"unreachable"


